export interface LetterRowDto { id: string; version: number; status: string }
/** Backend section keys that differ from the UI's ELGA list. */
const UI_KEY: Record<string, string> = { empfehlungen: "weitere", medikation_einweisung: "einweisung" };
const BACKEND_KEY: Record<string, string> = Object.fromEntries(Object.entries(UI_KEY).map(([b, u]) => [u, b]));
const uiSection = (key: string) => ELGA_SECTIONS.find((s) => s.key === (UI_KEY[key] ?? key));
const shown = (v: { text?: string | null; items?: LetterItemDto[] } | null) => (!v ? "" : v.text && v.text !== NO_DATA ? v.text : (v.items ?? []).map((i) => i.text).join("\n"));
function parseEdit(json: string | null): { text?: string | null; items?: LetterItemDto[] } | null {
  try { return json ? (JSON.parse(json) as { text?: string | null; items?: LetterItemDto[] }) : null; } catch { return null; }
}

/** Empty letter in the backend's section order, shown until a draft is created from the KIS. */
export const emptyLetter = (patient: string): LetterDocument => ({ id: `new:${patient}`, patient, sections: ELGA_SECTIONS.map((s) => ({ ...s, key: BACKEND_KEY[s.key] ?? s.key, items: [] })), texts: {}, edit_history: [], version: 1, status: "DRAFT" });
export const currentLetter = (rows: LetterRowDto[]) => [...rows].sort((a, b) => b.version - a.version).find((r) => r.status !== "superseded");

export function fromLetter(l: LetterDto): LetterDocument {
  const sections: ClinicalSection[] = l.content.sections.map((s) => {
    const ui = uiSection(s.key);
    return { key: s.key, title: ui?.title ?? s.heading, ...(s.required ? { required: true } : {}), ...(ui?.recommended ? { recommended: true } : {}),
      items: s.items.map((i) => ({ text: i.text, source: i.source ?? "KIS", sourceText: i.source ? `${i.text}\n\nSource: ${i.source}` : i.text })) };
  });
  const texts: Record<string, string> = Object.fromEntries(l.content.sections.filter((s) => s.last_edited_by).map((s) => [s.key, s.text === NO_DATA ? "" : s.text]));
  // Every saved edit counts as a version, as in the demo letter; the snapshots are rebuilt from the backend's edit log.
  const edits = l.edit_history ?? [];
  let state: Record<string, string> = Object.fromEntries(l.content.sections.map((s) => [s.key, texts[s.key] ?? s.items.map((i) => i.text).join("\n")]));
  const history: LetterEdit[] = [];
  for (const [i, e] of [...edits.entries()].reverse()) {
    const before = shown(parseEdit(e.before));
    state = { ...state, [e.section]: before };
    history.push({ id: `api-${e.id}`, version: l.version + i + 1, who: e.editor_name ?? "", role: l.content.header?.hospital ?? HOSPITAL, when: deDateTime(e.ts),
      section: uiSection(e.section)?.title ?? e.section, key: e.section, before, after: shown(parseEdit(e.after)), reason: e.reason ?? "", snapshot: { ...state } });
  }
  return {
    id: l.id, patient: l.patient_id, sections, texts, edit_history: history, version: l.version + edits.length, status: l.status === "draft" ? "DRAFT" : "SIGNED",
    ...(l.signed_at ? { signedAt: deDateTime(l.signed_at), signedBy: l.signed_by ?? "" } : {}),
    ...(l.supersedes ? { supersedes: l.version - 1 } : {}),
    generatedAt: l.created_at, generationSource: "FastAPI",
    ...(l.content.header?.stay?.from ? { stay: `Stay: ${deDate(l.content.header.stay.from)} – ${deDate(l.content.header.stay.to ?? "")}` } : {}),
  };
}

