/** A request plus its original Track-3 JSON, which is what the backend evaluates. */
export type LiveRequest = ResearchRequest & { raw?: Record<string, unknown> | undefined };
export interface SampleDto { id: string; applicant?: Org; purpose?: string | null; requested_as?: string | null; request: Record<string, unknown> }
export function fromSample(s: SampleDto): LiveRequest {
  return { id: s.id, applicant: orgOf(s.applicant), purpose: s.purpose ?? "", type: requestType(s.requested_as), text: String(s.request["question"] ?? ""), terms: [], sql: "-- Generated by the backend when the request is evaluated", raw: s.request };
}

const UI_ONLY = new Set(["applicant", "type", "text", "whyNotStatistics", "prohibitedPurpose", "metric", "results", "terms", "sql", "raw"]);
/** Track-3 request JSON: the original when known, otherwise built from the form. Extra fields such as definitions pass through. */
export function toBackendRequest(r: LiveRequest): Record<string, unknown> {
  if (r.raw) return r.raw;
  const extra = Object.fromEntries(Object.entries(r).filter(([k]) => !UI_ONLY.has(k)));
  return { ...extra, applicant: { organisation: r.applicant }, requested_as: extra["requested_as"] ?? r.type, question: extra["question"] ?? r.text, ...(r.whyNotStatistics ? { why_not_statistics: r.whyNotStatistics } : {}) };
}

export interface StatisticDto { id: string; label: string; kind: string; groups: { group: Record<string, string | number>; value: number | string | null }[] }
export interface EvaluationDto {
  request_id: string; decision: Decision; matched_step: 1 | 2 | 3 | 4; articles: (string | number)[];
  prohibited_purposes?: { purpose: string }[]; explanation?: Partial<Record<Lang, string>>;
  statistics?: StatisticDto[]; opted_out_excluded?: number;
  spe?: { id: string; patient_count: number | string; record_types: string[]; patient_ids_kept: boolean };
  permit_checklist?: { label: string; status: "yes" | "no" | "check"; reason: string }[];
  staff?: { term_mapping?: { term: string; system: string; codes: string[] }[]; sql?: { metric: string; sql: string }[] };
}
const groupLabel = (g: Record<string, string | number>) => Object.values(g).join(" · ") || "All patients";
/** One row per group and one column per requested figure; values arrive already protected (<10, suppressed). */
export function resultTable(stats: StatisticDto[] | undefined): ResultTable | undefined {
  if (!stats?.length) return undefined;
  const groups = [...new Set(stats.flatMap((s) => s.groups.map((g) => groupLabel(g.group))))];
  return {
    columns: stats.map((s) => ({ key: s.id, label: cap(s.label) + (s.kind === "percentage" ? " (%)" : "") })),
    rows: groups.map((group) => ({ group, cells: stats.map((s) => s.groups.find((g) => groupLabel(g.group) === group)?.value ?? null) })),
  };
}
const CHECK_STATUS = { yes: "pass", no: "fail", check: "pending" } as const;
export function fromEvaluation(d: EvaluationDto, req: ResearchRequest): Evaluation {
  const terms = d.staff?.term_mapping?.map((t) => ({ term: t.term, system: t.system, codes: t.codes.join(", "), found: t.codes.length > 0 }));
  const sql = d.staff?.sql?.map((q) => `-- ${q.metric}\n${q.sql}`).join("\n\n");
  const prohibited = d.prohibited_purposes?.[0]?.purpose;
  const table = resultTable(d.statistics);
  return {
    decision: d.decision, step: d.matched_step, articles: d.articles.map(article),
    ...(prohibited ? { prohibitedPurpose: prohibited } : {}),
    request: { ...req, terms: terms ?? req.terms, sql: sql ?? req.sql },
    ...(d.explanation ? { explanation: d.explanation } : {}),
    ...(table ? { table } : {}),
    ...(d.opted_out_excluded !== undefined ? { optedOutExcluded: d.opted_out_excluded } : {}),
    ...(d.spe ? { spe: { id: d.spe.id, patients: d.spe.patient_count, recordTypes: d.spe.record_types, idsKept: d.spe.patient_ids_kept } } : {}),
    ...(d.permit_checklist ? { checklist: d.permit_checklist.map((c) => ({ label: c.label, status: CHECK_STATUS[c.status], reason: c.reason })) } : {}),
  };
}

